# Windows: register vendor SDK directories on the DLL search path before
# importing the native extension.
#
# Windows extension modules (.pyd) have not consulted PATH for their DLL
# dependencies since Python 3.8 -- os.add_dll_directory() must be called
# explicitly for every directory containing a needed DLL, or the import
# fails with a generic "DLL load failed ... The specified module could not
# be found." that gives no hint which of the ~900+ transitive dependencies
# is missing.
#
# On top of that, a Windows loader quirk was found by hand: some of these
# vendor DLLs (confirmed for Intel oneAPI's SYCL/oneDNN runtime) fail to
# resolve their OWN nested dependencies through AddDllDirectory-registered
# search paths when loaded cold, but succeed immediately once those
# dependencies are already resident in the process. So beyond registering
# directories, a curated set of runtime DLLs is pre-loaded by name pattern
# before the native extension is imported.
#
# The directory list comes from _win_dll_dirs.py, generated by CMake at
# configure time from the exact SDK roots this build was configured against
# (see CMakeLists.txt) -- not hardcoded here, so it stays correct across
# oneAPI/CUDA/ROCm version bumps and different install layouts.
if _sys.platform == "win32":
    def _tenzor_win_bootstrap():
        try:
            from . import _win_dll_dirs as _manifest
            dll_dirs = list(_manifest.DLL_DIRS)
        except ImportError:
            # Manifest wasn't generated (e.g. a hand-rolled build setup that
            # doesn't go through CMakeLists.txt's Python bindings block).
            # Nothing to register; import may still fail below with the
            # normal DLL-not-found error.
            dll_dirs = []

        for _d in dll_dirs:
            if _os.path.isdir(_d):
                try:
                    _os.add_dll_directory(_d)
                except (OSError, AttributeError):
                    pass  # add_dll_directory requires Python >= 3.8

        import ctypes as _ctypes
        import glob as _glob
        # Name patterns for the runtime DLLs known to need pre-loading (see
        # module docstring above). A pattern matching nothing on this
        # machine (e.g. no ROCm installed) is simply skipped.
        _preload_patterns = (
            "libmmd.dll", "svml_dispmd.dll", "tbb12.dll", "tbb.dll",
            "ur_win_proxy_loader.dll", "sycl*.dll", "libiomp5md.dll",
            "mkl_core.*.dll", "mkl_intel_thread.*.dll", "mkl_tbb_thread.*.dll",
            "mkl_sequential.*.dll", "dnnl.dll",
            "nvrtc64_*.dll", "hiprtc*.dll", "amdhip64_*.dll",
        )
        for _d in dll_dirs:
            if not _os.path.isdir(_d):
                continue
            for _pattern in _preload_patterns:
                for _dll_path in _glob.glob(_os.path.join(_d, _pattern)):
                    try:
                        _ctypes.WinDLL(_dll_path)
                    except OSError:
                        pass

    _tenzor_win_bootstrap()
    del _tenzor_win_bootstrap

