# Windows: call finalize() deterministically via Python's own atexit, instead
# of relying solely on the C++ library's std::atexit(finalize) safety net.
# tenzor_core.finalize() is idempotent (a no-op past the first call), so this
# does not skip or duplicate that native registration -- it just makes the
# FIRST real call happen earlier and safely, while the interpreter is still
# fully alive, rather than racing against other DLLs' (confirmed: the SYCL
# runtime's) own exit-time cleanup in the C-runtime's process-wide atexit
# cascade -- which reproducibly corrupts the heap at process exit
# (STATUS_STACK_BUFFER_OVERRUN) once the OneAPI backend has real SYCL
# devices/queues to tear down. Verified with a minimal non-Python C++ repro:
# calling finalize() while still "running" never crashes; leaving only the
# native atexit-triggered call to fire during the real shutdown cascade
# always does.
if _sys.platform == "win32":
    import atexit as _atexit
    _atexit.register(finalize)
    del _atexit

# Audit E.10: module-level `from_numpy` convenience. Until now the .pyi
# advertised `tz.from_numpy(array, requires_grad=False)` but the runtime
# only exposed `tz.Tensor.from_numpy(...)`. Expose a thin top-level alias
# so the documented surface matches reality.
def from_numpy(array, requires_grad: bool = False):
    """Create a Tensor (or Variable, if ``requires_grad=True``) from a NumPy array.

    Mirrors ``torch.from_numpy``: zero-copy when the dtype and stride layout
    allow it, otherwise materialises a host copy. The returned tensor lives
    on CPU; move it explicitly with ``.to(device)``.

    .. warning::
        When the zero-copy path is taken, the returned tensor **shares
        memory with** the input NumPy array. With ``requires_grad=True``
        this aliasing extends into the autograd graph: the resulting leaf
        Variable's value is backed by the same buffer as ``array``. Mutating
        ``array`` in place afterwards (e.g. ``array[:] = ...``) silently
        changes the leaf's value out from under autograd, corrupting any
        forward results already computed and the gradients derived from
        them. This matches ``torch.from_numpy`` behaviour. If you intend to
        keep mutating the NumPy array, pass a copy (``array.copy()``) or
        detach the leaf before mutating.
    """
    from .tenzor_core import Tensor as _Tensor, Variable as _Variable
    t = _Tensor.from_numpy(array)
    if requires_grad:
        return _Variable(t, True)
    return t


# Audit B1 (follow-up): module-level ``to_torch`` / ``from_torch`` convenience.
# The C++ interop lives on the ``tenzor.torch_interop`` submodule as
# ``tensor_to_torch`` / ``tensor_from_torch``. These top-level aliases mirror
# ``from_numpy`` (Audit E.10): the documented surface is the short name, and
# delegating to the submodule keeps a single implementation. When the module
# was built without torch support, ``torch_interop`` is the unavailable proxy
# whose attribute access raises a clear ImportError, so the error path is
# preserved.
def to_torch(tensor, requires_grad: bool = False):
    """Convert a Tenzor ``Tensor`` to a PyTorch tensor.

    Delegates to ``tenzor.torch_interop.tensor_to_torch``: zero-copy when the
    dtype, contiguity and device allow it, otherwise materialises a copy.
    ``requires_grad`` requests a PyTorch tensor that tracks gradients.
    """
    return torch_interop.tensor_to_torch(tensor, requires_grad)


def from_torch(torch_tensor, device=None):
    """Convert a PyTorch tensor to a Tenzor ``Tensor``.

    Delegates to ``tenzor.torch_interop.tensor_from_torch``: zero-copy when
    possible, otherwise copies. ``device`` places the result on a specific
    Tenzor device; when ``None`` the PyTorch tensor's own device is honoured.
    """
    return torch_interop.tensor_from_torch(torch_tensor, device)


